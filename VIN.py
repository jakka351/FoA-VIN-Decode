"""
Australian Ford Falcon VIN Decoder
Coverage target: 2003-2016 BA / BF / FG / FG X

VIN layout implemented from documented Australian Falcon examples:
    1-3   WMI
    4-7   Ford-specific descriptor
    8     Plant-related code
    9-10  Body-style code
    11    Model-year code
    12    Production-month code
    13-17 Production sequence

- This is a Falcon-specific decoder, not a universal VIN decoder.
- Exact trim/variant requires verified Ford factory coding/build data.
- Validate field positions against the relevant factory workshop manual.
"""
from dataclasses import dataclass, asdict
from typing import Optional
import argparse
import json
import re


# ---------------------------------------------------------------------
# Manufacturer and Ford Falcon coding tables
# ---------------------------------------------------------------------

WMI_TABLE = {
    "6FP": {
        "manufacturer": "Ford Motor Company of Australia",
        "make": "Ford",
        "country": "Australia",
    }
}

BODY_CODES = {
    "SW": {
        "body_type": "Sedan",
        "wheelbase": "Standard",
        "description": "Falcon-family sedan",
    },
    "WA": {
        "body_type": "Wagon",
        "wheelbase": "Standard",
        "description": "Falcon-family station wagon",
    },
    "CM": {
        "body_type": "Utility",
        "wheelbase": "Standard",
        "description": "Falcon-family utility (ute)",
    },
    "LW": {
        "body_type": "Sedan",
        "wheelbase": "Long",
        "description": "Long-wheelbase Ford passenger vehicle",
    },
}

# Model-year codes for the requested range.
# These represent model-year codes, not necessarily calendar build year.
YEAR_CODES = {
    "3": 2003,
    "4": 2004,
    "5": 2005,
    "6": 2006,
    "7": 2007,
    "8": 2008,
    "9": 2009,
    "A": 2010,
    "B": 2011,
    "C": 2012,
    "D": 2013,
    "E": 2014,
    "F": 2015,
    "G": 2016,
}

# Common Ford-style month identifiers. Confirm against the relevant
# vehicle's factory identification documentation.
MONTH_CODES = {
    "A": "January",
    "B": "February",
    "C": "March",
    "D": "April",
    "E": "May",
    "F": "June",
    "G": "July",
    "H": "August",
    "J": "September",
    "K": "October",
    "L": "November",
    "M": "December",
}

PLANT_CODES = {
    "G": "Broadmeadows, Victoria (provisional mapping)",
}

# Approximate family date ranges.
# Boundary years intentionally return multiple candidates.
GENERATION_RANGES = {
    "BA": (2003, 2005),
    "BF": (2006, 2008),
    "FG": (2008, 2014),
    "FG X": (2014, 2016),
}

# IMPORTANT:
# Populate this table ONLY from verified factory identification data.
#
# The key is the actual Ford model/series/build code from an authoritative
# source (e.g. factory build record or applicable identification plate).
# Do not assume that a marketing badge is directly encoded in the VIN.
#
# Example schema:
#
# FACTORY_VARIANTS = {
#     ("FG", "VERIFIED_CODE"): {
#         "model": "Falcon",
#         "variant": "XR6 Turbo",
#         "engine": "4.0L turbocharged inline-six",
#         "fuel": "Petrol",
#         "source": "Ford FG identification documentation, page ..."
#     }
# }
#
FACTORY_VARIANTS = {}


@dataclass
class FalconVINResult:
    vin: str
    valid_format: bool
    manufacturer: Optional[str] = None
    make: Optional[str] = None
    country: Optional[str] = None
    wmi: Optional[str] = None
    descriptor: Optional[str] = None
    plant_code: Optional[str] = None
    assembly_plant: Optional[str] = None
    body_code: Optional[str] = None
    body_type: Optional[str] = None
    wheelbase: Optional[str] = None
    model_year: Optional[int] = None
    production_month: Optional[str] = None
    production_sequence: Optional[str] = None
    generation_candidates: Optional[list] = None
    model: Optional[str] = None
    variant: Optional[str] = None
    engine: Optional[str] = None
    fuel: Optional[str] = None
    factory_model_code: Optional[str] = None
    warnings: Optional[list] = None


def normalize_vin(vin: str) -> str:
    """Normalize whitespace and casing without silently altering characters."""
    return re.sub(r"\s+", "", vin).upper()


def get_generation_candidates(year: Optional[int]) -> list:
    """Return every generation range containing the model year."""
    if year is None:
        return []

    return [
        name
        for name, (start, end) in GENERATION_RANGES.items()
        if start <= year <= end
    ]


def decode_falcon_vin(
    vin: str,
    factory_model_code: Optional[str] = None,
    build_record: Optional[dict] = None,
) -> FalconVINResult:
    """
    Decode a Falcon VIN.

    factory_model_code:
        Optional verified factory series/model code. It must match a key
        in FACTORY_VARIANTS when used for exact variant identification.

    build_record:
        Optional trusted supplementary build data. Supported keys:
        generation, model, variant, engine, fuel, body_type, model_year,
        factory_model_code.

        Only supply values obtained from an authoritative build record.
    """
    vin = normalize_vin(vin)
    warnings = []

    if not re.fullmatch(r"[A-HJ-NPR-Z0-9]{17}", vin):
        raise ValueError(
            "VIN must contain 17 valid VIN characters. "
            "I, O and Q are excluded."
        )

    wmi = vin[0:3]
    descriptor = vin[3:7]
    plant_code = vin[7]
    body_code = vin[8:10]
    year_code = vin[10]
    month_code = vin[11]
    sequence = vin[12:17]

    manufacturer_info = WMI_TABLE.get(wmi, {})
    body_info = BODY_CODES.get(body_code, {})
    model_year = YEAR_CODES.get(year_code)

    result = FalconVINResult(
        vin=vin,
        valid_format=True,
        manufacturer=manufacturer_info.get("manufacturer"),
        make=manufacturer_info.get("make"),
        country=manufacturer_info.get("country"),
        wmi=wmi,
        descriptor=descriptor,
        plant_code=plant_code,
        assembly_plant=PLANT_CODES.get(plant_code),
        body_code=body_code,
        body_type=body_info.get("body_type"),
        wheelbase=body_info.get("wheelbase"),
        model_year=model_year,
        production_month=MONTH_CODES.get(month_code),
        production_sequence=sequence,
        generation_candidates=get_generation_candidates(model_year),
        factory_model_code=factory_model_code,
        warnings=warnings,
    )

    if wmi != "6FP":
        warnings.append(
            "WMI is not the configured Ford Australia Falcon identifier. "
            "Falcon-specific field interpretation may not apply."
        )

    if not body_info:
        warnings.append(
            f"Unrecognised body code {body_code!r}; "
            "consult the applicable factory identification manual."
        )

    if model_year is None:
        warnings.append(
            f"Year code {year_code!r} is outside the configured "
            "2003-2016 model-year table."
        )

    if len(result.generation_candidates or []) > 1:
        warnings.append(
            "Model year overlaps generation transition ranges. "
            "Use the build date and factory series code to resolve it."
        )

    if not result.generation_candidates:
        warnings.append(
            "Generation cannot be established from the configured "
            "model-year ranges."
        )

    # Decode exact variant only when a verified code is available.
    if factory_model_code:
        matched = FACTORY_VARIANTS.get(
            (result.generation_candidates[0], factory_model_code)
        ) if len(result.generation_candidates or []) == 1 else None

        if matched:
            result.model = matched.get("model")
            result.variant = matched.get("variant")
            result.engine = matched.get("engine")
            result.fuel = matched.get("fuel")
        else:
            warnings.append(
                "Factory model code was supplied but has no matching "
                "verified entry for an unambiguous generation."
            )

    # Trusted factory build data can resolve model/generation ambiguity.
    if build_record:
        allowed = {
            "generation",
            "model",
            "variant",
            "engine",
            "fuel",
            "body_type",
            "model_year",
            "factory_model_code",
        }

        for key, value in build_record.items():
            if key not in allowed:
                warnings.append(
                    f"Ignored unsupported build-record field: {key}"
                )
                continue

            if value is not None:
                setattr(result, key, value)

    # Explicitly avoid making up a trim from the VIN descriptor.
    if result.variant is None:
        result.variant = "Unknown — factory variant data required"

    if result.model is None and result.make == "Ford":
        result.model = "Falcon family (series unconfirmed)"

    if result.engine is None:
        warnings.append(
            "Engine displacement, aspiration and exact engine variant "
            "have not been established by this VIN decoder."
        )

    return result


def main():
    parser = argparse.ArgumentParser(
        description="Australian Ford Falcon VIN decoder (2003-2016)"
    )
    parser.add_argument("vin", help="17-character VIN")
    parser.add_argument(
        "--factory-model-code",
        help="Verified Ford factory model/series code",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Print machine-readable JSON",
    )

    args = parser.parse_args()

    try:
        result = decode_falcon_vin(
            args.vin,
            factory_model_code=args.factory_model_code,
        )
    except ValueError as exc:
        parser.error(str(exc))

    data = asdict(result)

    if args.json:
        print(json.dumps(data, indent=2))
        return

    print("=" * 60)
    print("AUSTRALIAN FORD FALCON VIN DECODER")
    print("=" * 60)

    for key, value in data.items():
        if key == "warnings":
            continue
        print(f"{key.replace('_', ' ').title():24}: {value}")

    if result.warnings:
        print("\nWarnings:")
        for warning in result.warnings:
            print(f"  - {warning}")


if __name__ == "__main__":
    main()
